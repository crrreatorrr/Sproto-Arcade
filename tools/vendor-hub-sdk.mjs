#!/usr/bin/env node
// Vendor @metaverse/hub-sdk into Sproto Arcade as one classic script.
//   node tools/vendor-hub-sdk.mjs <path-to-metaverse-hub>
// Story mode is classic scripts that also run from file://, so the SDK's ES modules are
// bundled with the hub's own esbuild into vendor/hub-sdk/hub-sdk.iife.js, which sets
// `window.HubSdk`. Only what the Arcade uses is exported. VENDOR.md records the source.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');
const hub = resolve(process.argv[2] ?? '../metaverse-hub');
const pkgDir = join(hub, 'packages/hub-sdk');
if (!existsSync(join(pkgDir, 'package.json'))) {
  console.error(`usage: node tools/vendor-hub-sdk.mjs <path-to-metaverse-hub> (no packages/hub-sdk in ${hub})`);
  process.exit(2);
}
const esbuild = join(hub, 'node_modules/.bin/esbuild');
if (!existsSync(esbuild)) {
  console.error('run `npm ci` in metaverse-hub first (esbuild comes with its Vite toolchain)');
  process.exit(2);
}
execFileSync('npm', ['run', 'build', '-w', '@metaverse/hub-sdk'], { cwd: hub, stdio: 'inherit' });
const git = (...a) => execFileSync('git', ['-C', hub, ...a], { encoding: 'utf8' }).trim();
const sha = git('rev-parse', '--short', 'HEAD');
const branch = git('rev-parse', '--abbrev-ref', 'HEAD');
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;

const outDir = join(repo, 'vendor/hub-sdk');
mkdirSync(outDir, { recursive: true });
const entry = join(outDir, '.entry.mjs');
writeFileSync(
  entry,
  `export { createHubSdk, HubEvent, HubSdkError, RELIC_IDS, GAME_IDS, SAVE_MAX_BYTES, encodeSave, relicForEvent } from ${JSON.stringify(join(pkgDir, 'dist/index.js'))};\n`,
);
const out = join(outDir, 'hub-sdk.iife.js');
execFileSync(esbuild, [entry, '--bundle', '--format=iife', '--global-name=HubSdk', '--target=es2020', '--legal-comments=none', `--outfile=${out}`], {
  stdio: 'inherit',
});
execFileSync('rm', ['-f', entry]);
const banner = `/* @metaverse/hub-sdk ${version} from crrreatorrr/metaverse-hub ${branch} ${sha}. Generated by tools/vendor-hub-sdk.mjs; do not edit. */\n`;
writeFileSync(out, banner + readFileSync(out, 'utf8'));
writeFileSync(
  join(outDir, 'VENDOR.md'),
  `# Vendored @metaverse/hub-sdk

- repo: https://github.com/crrreatorrr/metaverse-hub
- branch: ${branch}
- sha: ${sha}
- package: packages/hub-sdk @ ${version}
- built with: \`node tools/vendor-hub-sdk.mjs <path-to-metaverse-hub>\`

Story mode (\`legacy.html\`) is classic scripts and also runs from \`file://\`, so the SDK is one
IIFE bundle, \`hub-sdk.iife.js\`, that sets \`window.HubSdk\`. It exports \`createHubSdk\`,
\`HubEvent\`, \`HubSdkError\`, \`RELIC_IDS\`, \`GAME_IDS\`, \`SAVE_MAX_BYTES\`, \`encodeSave\` and
\`relicForEvent\`. \`hub-link.js\` is the only caller.

Re-vendor whenever packages/hub-sdk changes, and after the hub PR merges re-vendor from hub main.
The SDK drops Relic ids it does not know, so an old bundle hides newer Relics.
`,
);
console.log(`wrote ${out} (${readFileSync(out).length} bytes) from ${branch} ${sha}`);
