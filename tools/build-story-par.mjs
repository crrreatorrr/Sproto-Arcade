#!/usr/bin/env node
// Writes story-par.js: the par time per story level, used for the clear-screen rank (S and A
// need a time at or near par; story-progress.js rankFor). Par is the golden bot's clear time
// x 1.25, so run this whenever qa/golden/story-NN.json is regenerated.
//   node tools/build-story-par.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export const PAR_FACTOR=1.25;
export function storyParSource(){
  const directory=path.join(root,'qa/golden');
  const rows=fs.readdirSync(directory).filter(f=>/^story-\d\d\.json$/.test(f)).sort().map(f=>JSON.parse(fs.readFileSync(path.join(directory,f),'utf8')))
    .map(gold=>[gold.level,Math.round(gold.expect.ticks*PAR_FACTOR)]).sort((a,b)=>a[0]-b[0]);
  return '/* Generated by tools/build-story-par.mjs from qa/golden: par ticks per level id = the golden bot\'s\n'+
    ' * clear ticks x '+PAR_FACTOR+'. Browser only; the simulation never reads it. Do not edit by hand. */\n'+
    'const STORY_PAR_TICKS=Object.freeze({'+rows.map(([level,ticks])=>level+':'+ticks).join(',')+'});\n';
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const file=path.join(root,'story-par.js'),source=storyParSource();
  if(process.argv.includes('--check')){
    if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==source){console.error('story-par.js is stale: run node tools/build-story-par.mjs');process.exit(1);}
    console.log('story-par.js matches qa/golden');
  }else{fs.writeFileSync(file,source);console.log(source.trim().split('\n').at(-1));}
}
